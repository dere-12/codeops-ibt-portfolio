import type { Area, Order, OrderStatus } from './order.types';

function createSeedOrder(
  id: string,
  customerName: string,
  area: Area,
  status: OrderStatus,
  dishName: string,
  priceSantim: number,
): Order {
  return {
    id,
    customerName,
    area,
    status,
    dishes: [{ name: dishName, priceSantim }],
    totalSantim: priceSantim,
  };
}

